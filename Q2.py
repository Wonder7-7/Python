#WAP to accept two numbers from the user and display their
#sum, difference, product, quotient and remainder.

num1 = int(input("Enter a number: "))
num2 = int(input("Enter another number: "))

print(f"{num1} + {num2} = {num1+num2}")
print(f"{num1} - {num2} = {num1-num2}")
print(f"{num1}*{num2} = {num1*num2}")
print(f"{num1}//{num2} = {num1/num2}")
print(f"{num1}%{num2} = {num1%num2}")
